/**
 * The settings' text (SET-1): `<generated>/settings.ts` (the declaration as data, the typed `Settings`, `loadSettings`
 * and the `settings` system) and `.env.example`, both printed from `deriveProjectSettings` and nothing else.
 */

import { settingOwnerLabel, settingsByGroup, type ProjectSetting } from '../../derived/settings/index.js';

/** The first words of the `.env.example` codegen writes: a file that starts with them is codegen's to rewrite. */
const ENV_EXAMPLE_BANNER = '# @generated by @pattern-stack/codegen';

/** Is this `.env.example` codegen's (it starts with the banner), not one the project curates? */
export function isGeneratedEnvExample(text: string): boolean {
	return text.startsWith(ENV_EXAMPLE_BANNER);
}

/** The module that holds the settings and the `settings` system, beside `wiring.ts`. */
export const SETTINGS_FILE = 'settings.ts';

const quote = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** A description on one line, safe inside a block comment and after a `#`. */
const oneLine = (s: string): string => s.replace(/\s+/g, ' ').trim().replace(/\*\//g, '*\\/');

/** `<generated>/settings.ts`. `runtimeSettingsImport` is `runtimeImport(mode, 'settings')`. */
export function settingsContent(settings: readonly ProjectSetting[], runtimeSettingsImport: string, banner: string): string {
	const groups = [...settingsByGroup(settings)];
	const body = groups
		.map(([group, list]) => {
			const entries = list
				.map((s) => {
					const fields = [
						`env: ${quote(s.env)}`,
						`secret: ${s.secret}`,
						...(s.default !== undefined ? [`default: ${quote(s.default)}`] : []),
						`format: ${quote(s.format)}`,
					];
					return `    /** ${oneLine(s.description)} (${settingOwnerLabel(s.owner)}) */\n    ${s.key}: { ${fields.join(', ')} },`;
				})
				.join('\n');
			return `  ${group}: {\n${entries}\n  },`;
		})
		.join('\n');
	return `${banner}
/**
 * Every value this app reads at startup (SET-1), declared in the YAML: a provider's \`settings:\` and
 * \`client.base_url\`, each installed subsystem's, and the project's. \`codegen project settings\` lists them with
 * whether each is set; \`.env.example\` is written from the same list.
 *
 * The \`settings\` system loads them all through one schema when the app is composed, and fails once, naming every
 * missing or malformed value. Read them as \`app.system('settings')\`, or as a system's \`uses: ['settings']\`.
 */
import { loadSettings as load, projectSource, type SettingsOf, type SettingsSource } from '${runtimeSettingsImport}';
import { defineSystem } from './wiring';

export const SETTINGS = {
${body}
} as const;

export type Settings = SettingsOf<typeof SETTINGS>;

/**
 * Load and check every setting. \`source\` defaults to the project's: the environment, then \`.env\` and \`.env.config\`
 * in the working directory (what \`codegen project settings\` reads, so its check and this load agree).
 */
export function loadSettings(source: SettingsSource = projectSource()): Settings {
  return load(SETTINGS, source);
}

export const settingsSystem = defineSystem({
  name: 'settings',
  uses: [],
  create: (): Settings => loadSettings(),
});
`;
}

/** `.env.example`: every setting, by owner. Secrets blank; a default commented out, so a copy sets only what must be. */
export function envExampleContent(settings: readonly ProjectSetting[]): string {
	const owners: Array<[string, ProjectSetting[]]> = [];
	for (const s of settings) {
		const label = settingOwnerLabel(s.owner);
		const last = owners[owners.length - 1];
		if (last && last[0] === label) last[1].push(s);
		else owners.push([label, [s]]);
	}
	const blocks = owners.map(([label, list]) => {
		const lines = list.map((s) => {
			const what = `# ${s.group}.${s.key}${s.secret ? ' (secret)' : ''}: ${oneLine(s.description)}`;
			const value = s.default !== undefined ? `# ${s.env}=${s.default}` : `${s.env}=`;
			return `${what}\n${value}`;
		});
		return `# ── ${label} ──\n${lines.join('\n')}`;
	});
	return `${ENV_EXAMPLE_BANNER} from the project's settings — DO NOT EDIT. Regenerate with \`codegen entity new --all\`.
# Copy to .env and fill in what is blank (\`codegen project settings --check\` names what is missing).
# A secret is blank; a value with a default is commented out with it.

${blocks.join('\n\n')}
`;
}
