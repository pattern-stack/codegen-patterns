const COMPOSITION_BANNER = '// AUTO-GENERATED by @pattern-stack/codegen. Do not edit.\n// Run `codegen entity new --all` to refresh.';

export interface PatternStackCompositionDirs {
	entitiesDir: string;
	relationshipsDir: string;
	generatedDir: string;
}

function relationsOf(ctx: Context, dirs: PatternStackCompositionDirs) {
	return loadProjectApiContext(ctx.cwd, ctx.config as RelationsConfigInput | null | undefined, {
		entitiesDir: dirs.entitiesDir,
		junctionsDir: junctionsDirFor(ctx.cwd),
		relationshipsDir: dirs.relationshipsDir,
	}).relations;
}

/** Is the events subsystem installed (S-1)? `isSubsystemInstalled`'s one rule (under pattern-stack, its `core.ts`). */
export function eventsInstalled(ctx: Context): boolean {
	return isSubsystemInstalled(ctx, 'events');
}

/** Is the integration subsystem installed (S-3)? `isSubsystemInstalled`'s one rule. */
export function integrationInstalled(ctx: Context): boolean {
	return isSubsystemInstalled(ctx, 'integration');
}

export function authInstalled(ctx: Context): boolean {
	return isSubsystemInstalled(ctx, 'auth');
}

/** The `auth` system's input (S-2), or null when the subsystem isn't installed. */
export function patternStackAuthInput(ctx: Context): CompositionAuthInput | null {
	return authInstalled(ctx) ? { coreImport: subsystemCoreImport(resolveRuntimeMode(ctx.config), 'auth') } : null;
}

/**
 * The vendored auth-integrations store (S-2): `<modules_dir>/connections/connection-store.ts`, or null when the starter
 * isn't vendored. The starter is always vendored (in package mode too), so its file is the record.
 */
export function connectionStoreFile(ctx: Context): string | null {
	const file = path.join(projectLayout(ctx.cwd, ctx.config).modules, 'connections', CONNECTION_STORE_FILE);
	return fs.existsSync(file) ? file : null;
}

/** The `connections` system's input (S-2), or null when the starter isn't vendored. */
export function patternStackConnectionsInput(ctx: Context): CompositionConnectionsInput | null {
	const storeFile = connectionStoreFile(ctx);
	return storeFile ? { storeFile } : null;
}

export function jobsInstalled(ctx: Context): boolean {
	return isSubsystemInstalled(ctx, 'jobs');
}

export function bridgeInstalled(ctx: Context): boolean {
	return isSubsystemInstalled(ctx, 'bridge');
}

/** The `integration` system's input (S-3), or null when the subsystem isn't installed. */
export function patternStackIntegrationInput(ctx: Context): CompositionIntegrationInput | null {
	if (!integrationInstalled(ctx)) return null;
	const mode = resolveRuntimeMode(ctx.config);
	const integration = configOrDefaults(ctx.config).integration ?? {};
	return {
		backend: integration.backend ?? 'drizzle',
		multiTenant: integration.multi_tenant ?? false,
		...(integration.differ ? { differ: integration.differ } : {}),
		coreImport: subsystemCoreImport(mode, 'integration'),
		runtimeImport: (relpath) => runtimeImport(mode, relpath),
	};
}

/** The `events` system's input (S-1), or null when the subsystem isn't installed. */
export function patternStackEventsInput(ctx: Context, generatedDir: string): CompositionEventsInput | null {
	if (!eventsInstalled(ctx)) return null;
	const mode = resolveRuntimeMode(ctx.config);
	const events = configOrDefaults(ctx.config).events ?? {};
	const backend = events.backend ?? 'drizzle';
	return {
		backend,
		multiTenant: events.multi_tenant ?? false,
		listenNotify: events.extensions?.drizzle?.listen_notify ?? false,
		backendImport: runtimeImport(mode, `subsystems/events/event-bus.${backend}-backend`),
		coreImport: subsystemCoreImport(mode, 'events'),
		generatedEventsDir: eventsGeneratedDir(ctx, generatedDir),
	};
}

/**
 * The integration set's input (S-3): the providers (`definitions/providers/`) and the entity YAMLs, or null with no
 * provider. The provider set was validated by the pre-flight; this reads it again, so the composition every command
 * writes (`entity new`, `junction new`) lists the same systems.
 */
function integrationsSource(ctx: Context, entitiesDir: string): PatternStackIntegrationsInput | null {
	const layout = projectLayout(ctx.cwd, ctx.config);
	const loaded = loadEntitiesFromYaml(listEntityYamls(entitiesDir, layout.nonEntityDirs));
	const entities = loaded.successes.map((s) => s.definition);
	const providers = loadProviderSet({
		providersDir: layout.providers,
		entitySurfaces: collectEntitySurfaces(entities),
		skipImportCheck: true,
	});
	// `entity new`'s pre-flight stops on these; `junction new` and a dry run reach here without it, and a provider that
	// failed to load must not just drop out of the composition.
	const blocking = providers.issues.filter((i) => i.severity === 'error');
	if (blocking.length > 0) {
		throw new Error(
			`[codegen] definitions/providers: ${blocking.map((i) => `${i.message}${i.path ? ` (${i.path})` : ''}`).join('; ')}`,
		);
	}
	if (providers.skipped || providers.loaded.length === 0) return null;
	return {
		providers: providers.loaded,
		entities: entities as PatternStackIntegrationsInput['entities'],
		outputRoot: integrationsRoot(layout),
		backendSrcAbs: layout.backendSrc,
		modulesAbs: layout.modules,
		mode: resolveRuntimeMode(ctx.config),
	};
}

/** Write (or, on a dry run, plan) the pattern-stack integration files (S-3), or null with no provider. The `integrations` module is the composition's. */
export function writePatternStackIntegrations(
	ctx: Context,
	dirs: { entitiesDir: string; generatedDir: string; aliases?: Record<string, string>; dryRun?: boolean },
): EmitPatternStackIntegrationsResult | null {
	const source = integrationsSource(ctx, dirs.entitiesDir);
	if (!source) return null;
	return emitPatternStackIntegrations({
		...source,
		wiringFile: path.join(dirs.generatedDir, 'wiring.ts'),
		aliases: dirs.aliases ?? {},
		tenancyColumn: TenancyConfigSchema.parse(ctx.config?.tenancy ?? {}).column,
		// S-2: with the starter vendored, each provider's factory takes the connection store.
		connectionStoreFile: connectionStoreFile(ctx),
		dryRun: dirs.dryRun ?? false,
	});
}

/**
 * The composition's input for this project: the one place that builds it. Every directory comes from `ctx`
 * (`projectLayout`, the junctions and relationships folders), and the relations load once per call.
 */
function compositionInput(ctx: Context): CompositionInput {
	const mode = resolveRuntimeMode(ctx.config);
	const layout = projectLayout(ctx.cwd, ctx.config);
	return {
		relations: loadProjectApiContext(ctx.cwd, ctx.config as RelationsConfigInput | null | undefined, {
			entitiesDir: layout.entities,
			junctionsDir: junctionsDirFor(ctx.cwd),
			relationshipsDir: relationshipsDirFor(ctx.cwd),
		}).relations,
		modulesDir: layout.modules,
		generatedDir: layout.generated,
		...emitterOptions(mode),
		events: patternStackEventsInput(ctx, layout.generated),
		integration: patternStackIntegrationInput(ctx),
		auth: patternStackAuthInput(ctx),
		connections: patternStackConnectionsInput(ctx),
		integrations: (() => {
			const source = integrationsSource(ctx, layout.entities);
			return source ? planPatternStackIntegrations(source) : null;
		})(),
		settings: { settings: projectSettings(ctx), runtimeImport: runtimeImport(mode, 'settings') },
	};
}

/** The emitter's options that follow from the runtime mode alone: every composition, `project init`'s empty one too. */
function emitterOptions(mode: RuntimeMode): Pick<CompositionInput, 'drizzleTypeImport' | 'openApiImport' | 'banner'> {
	return { drizzleTypeImport: runtimeImport(mode, 'types/drizzle'), openApiImport: openApiImport(mode), banner: CODEGEN_BANNER };
}

/** The pattern-stack composition for this project, planned (a dry run). Throws its refusals (a cycle, a name). */
export function planPatternStackComposition(ctx: Context): CompositionFile[] {
	return emitComposition({ ...compositionInput(ctx), dryRun: true });
}

/**
 * The composition of a project with no entity yet (PW-4): `project init` writes it, so the app's `compose.ts` and
 * `main.ts` compile before the first `entity new`, which rewrites it. The same emitter, over an empty set.
 */
export function emptyPatternStackComposition(
	dirs: { modulesDir: string; generatedDir: string },
	mode: RuntimeMode,
): CompositionFile[] {
	return emitComposition({
		// No entity, no junction; the tenancy column is the schema's default, as a config without `tenancy:` reads it.
		relations: { entities: [], definitions: new Map(), junctions: [], tenancyColumn: TenancyConfigSchema.parse({}).column },
		modulesDir: dirs.modulesDir,
		generatedDir: dirs.generatedDir,
		...emitterOptions(mode),
		// SET-1: the project's own settings (the database URL); the first `entity new` adds the providers' and subsystems'.
		settings: {
			settings: deriveProjectSettings({ providers: [], installedSubsystems: [] }),
			runtimeImport: runtimeImport(mode, 'settings'),
		},
		dryRun: true,
	});
}

export interface PatternStackCompositionResult {
	files: CompositionFile[];
	/** The other wiring's generated files, and any context module no longer composed, removed. */
	removed: string[];
	/** The entities and junctions whose `.wiring.ts` is missing or older than the composition (`wiringFilesBehind`). */
	behind: string[];
}

/** Write the composition, remove what it replaces, and name the `.wiring.ts` files it can't compile against. */
export function writePatternStackComposition(ctx: Context): PatternStackCompositionResult {
	const input = compositionInput(ctx);
	const files = emitComposition(input);
	const removed = removeOtherWiringFiles({
		wiring: 'pattern-stack',
		modulesDir: input.modulesDir,
		generatedDir: input.generatedDir,
		integrationsDir: integrationsRoot(projectLayout(ctx.cwd, ctx.config)),
		// The composition's files and the integration systems this run writes (`emitPatternStackIntegrations`).
		keep: new Set([...files.map((f) => f.path), ...(input.integrations?.systems ?? []).map((s) => s.file)]),
	});
	const behind = wiringFilesBehind(input);
	// SET-1: `.env.example` from the same settings as `<generated>/settings.ts`.
	writeEnvExample(ctx, projectSettings(ctx));
	return { files, removed, behind };
}

export function printPatternStackComposition(ctx: Context, result: PatternStackCompositionResult): void {
	for (const f of result.files) printInfo(`composition: ${path.relative(ctx.cwd, f.path)}`);
	for (const f of result.removed) {
		printInfo(`removed (wiring: nest output, or a context no longer composed): ${path.relative(ctx.cwd, f)}`);
	}
	if (result.behind.length > 0) {
		printWarning(
			`the composition imports from every entity's and junction's .wiring.ts, and these are missing or were written ` +
				`by an older codegen: ${result.behind.join(', ')}. Run \`entity new --all\` and \`junction new --all\`.`,
		);
	}
}
