/**
 * Switching `target.wiring` with integrations (S-3): the other wiring's generated integration files are removed, a
 * hand-written file never is, and the other wiring's author-owned scaffolds are named, not removed.
 */
import { describe, expect, it } from 'bun:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { otherWiringScaffolds, removeOtherWiringFiles } from '../../../emitters/composition/stale-files';

const GEN = '// @generated by @pattern-stack/codegen — DO NOT EDIT.\n';

function project(files: Record<string, string>): string {
	const root = fs.mkdtempSync(path.join(os.tmpdir(), 'stale-integ-'));
	for (const [rel, content] of Object.entries(files)) {
		fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
		fs.writeFileSync(path.join(root, rel), content);
	}
	return root;
}

const NEST_TREE = {
	'src/integrations/providers/acme/acme.provider.module.ts': GEN,
	'src/integrations/crm/crm-adapters.module.ts': GEN,
	'src/integrations/crm/crm-adapters.tokens.ts': GEN,
	'src/integrations/crm/adapters/index.ts': GEN,
	'src/integrations/crm/modules/acme/contact-integration.module.ts': GEN,
	'src/integrations/crm/sinks/contact.sink.generated.ts': GEN,
	'src/integrations/crm/adapters/acme/acme-crm.adapter.ts': "// <CODEGEN-SCAFFOLD-V1>\nimport { Injectable } from '@nestjs/common';\n",
	'src/integrations/crm/hand-written.module.ts': 'export {};\n',
};
const PS_TREE = {
	'src/integrations/providers/acme/acme.provider.ts': GEN,
	'src/integrations/providers/acme/acme.provider.factory.ts': '// <CODEGEN-SCAFFOLD-V1>\n',
	'src/integrations/crm/crm-adapters.system.ts': GEN,
	'src/integrations/module.ts': '// AUTO-GENERATED by @pattern-stack/codegen. Do not edit.\n',
	'src/integrations/crm/sinks/contact.sink.generated.ts': GEN,
	'src/integrations/crm/adapters/acme/acme-crm.adapter.ts': '// <CODEGEN-SCAFFOLD-V1>\nexport class AcmeCrmAdapter {}\n',
};

const remove = (root: string, wiring: 'nest' | 'pattern-stack') =>
	removeOtherWiringFiles({
		wiring,
		modulesDir: path.join(root, 'src/modules'),
		generatedDir: path.join(root, 'src/generated'),
		integrationsDir: path.join(root, 'src/integrations'),
	}).map((f) => path.relative(root, f)).sort();

describe('switching wiring with integrations', () => {
	it("going pattern-stack removes Nest's generated modules, tokens and barrels; keeps the sinks and hand-written files", () => {
		const root = project(NEST_TREE);
		expect(remove(root, 'pattern-stack')).toEqual([
			'src/integrations/crm/adapters/index.ts',
			'src/integrations/crm/crm-adapters.module.ts',
			'src/integrations/crm/crm-adapters.tokens.ts',
			'src/integrations/crm/modules/acme/contact-integration.module.ts',
			'src/integrations/providers/acme/acme.provider.module.ts',
		]);
		expect(fs.existsSync(path.join(root, 'src/integrations/crm/hand-written.module.ts'))).toBe(true);
		expect(otherWiringScaffolds('pattern-stack', path.join(root, 'src/integrations')).map((f) => path.relative(root, f))).toEqual([
			'src/integrations/crm/adapters/acme/acme-crm.adapter.ts',
		]);
	});

	it("going nest removes the pattern-stack systems and module; names the factories and plain adapters", () => {
		const root = project(PS_TREE);
		expect(remove(root, 'nest')).toEqual([
			'src/integrations/crm/crm-adapters.system.ts',
			'src/integrations/module.ts',
			'src/integrations/providers/acme/acme.provider.ts',
		]);
		expect(otherWiringScaffolds('nest', path.join(root, 'src/integrations')).map((f) => path.relative(root, f)).sort()).toEqual([
			'src/integrations/crm/adapters/acme/acme-crm.adapter.ts',
			'src/integrations/providers/acme/acme.provider.factory.ts',
		]);
	});
});
